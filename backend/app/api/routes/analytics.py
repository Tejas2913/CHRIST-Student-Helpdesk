# ---------------------------------------------------------------------------
# Retrieval eval report (from benchmark)
# ---------------------------------------------------------------------------

@router.get("/eval")
def analytics_eval():
    if _EVAL_REPORT.exists():
        try:
            with open(_EVAL_REPORT, encoding="utf-8") as fh:
                return json.load(fh)
        except Exception as e:
            logger.error("Failed to read eval report: %s", e)
    return {"error": "Retrieval eval report not found. Run the benchmark first."}


# ---------------------------------------------------------------------------
# CSV export
# ---------------------------------------------------------------------------

@router.get("/export/csv")
def analytics_export_csv(
    model: Optional[str] = None,
    status: Optional[str] = None,
    date_from: Optional[str] = None,
    date_to: Optional[str] = None,
):
    rows = export_csv_rows(model=model, status=status, date_from=date_from, date_to=date_to)

    output = io.StringIO()
    if rows:
        writer = csv.DictWriter(output, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    else:
        output.write("No data\n")

    output.seek(0)
    return StreamingResponse(
        iter([output.getvalue()]),
        media_type="text/csv",
        headers={"Content-Disposition": "attachment; filename=analytics_export.csv"},
    )
