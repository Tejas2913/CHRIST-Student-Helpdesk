"""
Analytics API routes — /api/analytics/...
All data comes from the SQLite analytics DB backed by real query logs.
"""

import csv
import io
import json
import logging
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, Query
from fastapi.responses import StreamingResponse

from app.analytics.db import (
    get_summary,
    get_model_stats,
    get_query_logs,
    get_query_detail,
    get_volume_over_time,
    get_latency_trend,
    get_category_distribution,
    get_error_breakdown,
    export_csv_rows,
)

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/analytics", tags=["analytics"])

# Path to retrieval eval report generated by the benchmark
_EVAL_REPORT = Path(__file__).resolve().parents[4] / "eval" / "retrieval_eval_report.json"


# ---------------------------------------------------------------------------
# KPI Summary
# ---------------------------------------------------------------------------

@router.get("/summary")
def analytics_summary():
    """Top-level KPI cards."""
    return get_summary()


# ---------------------------------------------------------------------------
# Per-model comparison
# ---------------------------------------------------------------------------

@router.get("/models")
def analytics_models():
    """Per-model aggregated statistics for comparison cards."""
    return get_model_stats()


# ---------------------------------------------------------------------------
# Query log (paginated)
# ---------------------------------------------------------------------------

@router.get("/queries")
def analytics_queries(
    page: int = Query(1, ge=1),
    limit: int = Query(50, ge=1, le=200),
    model: Optional[str] = None,
    status: Optional[str] = None,
    date_from: Optional[str] = None,
    date_to: Optional[str] = None,
    search: Optional[str] = None,
    query_type: Optional[str] = None,
    sort_by: str = "timestamp",
    sort_dir: str = "desc",
):
    rows, total = get_query_logs(
        page=page,
        limit=limit,
        model=model,
        status=status,
        date_from=date_from,
        date_to=date_to,
        search=search,
        query_type=query_type,
        sort_by=sort_by,
        sort_dir=sort_dir,
    )
    return {
        "data": rows,
        "total": total,
        "page": page,
        "limit": limit,
        "pages": max(1, (total + limit - 1) // limit),
    }


# ---------------------------------------------------------------------------
# Query detail
# ---------------------------------------------------------------------------

@router.get("/queries/{request_id}")
def analytics_query_detail(request_id: str):
    row = get_query_detail(request_id)
    if row is None:
        from fastapi import HTTPException
        raise HTTPException(status_code=404, detail="Query not found")
    return row


